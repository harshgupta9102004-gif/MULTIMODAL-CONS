# Gemini API Multi-Modal Client
# ---------------------------------------------------------
def call_gemini_rest(prompt: str, image_bytes: bytes = None, mime_type: str = "image/jpeg", api_key: str = "") -> dict:
    if not api_key:
        raise ValueError("No API Key provided")
    
    parts = []
    if image_bytes:
        encoded = base64.b64encode(image_bytes).decode("utf-8")
        parts.append({
            "inline_data": {
                "mime_type": mime_type,
                "data": encoded
            }
        })
    parts.append({"text": prompt})
    
    payload = {
        "contents": [{"role": "user", "parts": parts}],
        "generationConfig": {
            "temperature": 0.2,
            "response_mime_type": "application/json"
        }
    }
    
    models = ["gemini-2.5-flash", "gemini-1.5-flash"]
    last_err = None
    
    for model in models:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={api_key}"
        try:
            res = requests.post(url, json=payload, headers={"Content-Type": "application/json"}, timeout=35)
            if res.status_code == 200:
                data = res.json()
                text = data["candidates"][0]["content"]["parts"][0]["text"].strip()
                if text.startswith("```json"):
                    text = text[len("```json"):].strip()
                elif text.startswith("```"):
                    text = text[3:].strip()
                if text.endswith("```"):
                    text = text[:-3].strip()
                parsed = json.loads(text)
                parsed["demo_mode"] = False
                parsed["disclaimer"] = PRELIMINARY_DISCLAIMER
                return parsed
            else:
                last_err = f"{model} status {res.status_code}: {res.text}"
        except Exception as e:
            last_err = str(e)
            
    raise RuntimeError(f"Gemini API failure: {last_err}")


